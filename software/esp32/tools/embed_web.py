#!/usr/bin/env python3
"""Gzip the files in ../web and write them into ../diskohedron/web_assets.h.

Run this after every change to the web UI, then compile/flash the firmware.
The UI ends up inside the firmware, so there is no separate filesystem upload.
"""
import gzip
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
OUT = ROOT / "diskohedron" / "web_assets.h"

FILES = [
    ("index.html", "ASSET_INDEX_HTML", "text/html; charset=utf-8"),
    ("app.js", "ASSET_APP_JS", "application/javascript"),
    ("style.css", "ASSET_STYLE_CSS", "text/css"),
]


def main():
    lines = [
        "// generated by tools/embed_web.py - do not edit, edit ../web/ instead",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct WebAsset {",
        "\tconst char *mime;",
        "\tconst uint8_t *data;",
        "\tsize_t len;",
        "};",
        "",
    ]
    for name, ident, mime in FILES:
        raw = (WEB / name).read_bytes()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        lines.append(f"// {name}: {len(raw)} bytes, {len(gz)} gzipped")
        lines.append(f"static const uint8_t {ident}_DATA[] PROGMEM = {{")
        for i in range(0, len(gz), 20):
            lines.append("\t" + ", ".join(f"0x{b:02x}" for b in gz[i:i + 20]) + ",")
        lines.append("};")
        lines.append(f'static const WebAsset {ident} = {{"{mime}", {ident}_DATA, sizeof({ident}_DATA)}};')
        lines.append("")
        print(f"{name:12s} {len(raw):6d} -> {len(gz):6d} bytes")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
